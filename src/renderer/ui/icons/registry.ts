/** The component for a name and size (falls back to the nearest size the set has). */
export function iconComponent(name: IconName, size: IconSize, filled = false): FluentIcon {
  const v: Variants = ICONS[name];
  const pick = filled && (size === 16 || size === 20) ? v.f[size] : undefined;
  return pick ?? v.r[size] ?? v.r[20] ?? v.r[24]!;
}
